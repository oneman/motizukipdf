#!/bin/sh
# Tests of the guided IUT explorer: model self-check, the tour runs to the end,
# and the C engine and its JavaScript port give the same facts.
set -e
cd "$(dirname "$0")"
make -s -C c
c/iutx check
c/iutx tour > /dev/null
# the committed web data must match the C model
( printf '// GENERATED by `make -C explorer/c data` from explorer/c/model.c. Do not edit.\nconst IUTX_MODEL = '
  c/iutx json model
  printf ';\nif (typeof module !== "undefined") module.exports = IUTX_MODEL;\n' ) | cmp -s - web/data.js \
  || { echo "web/data.js is stale: run make -C explorer/c data"; exit 1; }
node web/test.js
echo "explorer: all tests passed"
