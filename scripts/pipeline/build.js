#!/usr/bin/env node
/*
 * scripts/pipeline/build.js — run the worked examples of initial Θ-data through the whole toolkit.
 *
 *   make -C src && node scripts/pipeline/build.js
 *
 * For every example listed in docs/initial-theta-data/index.json (the exact initial Θ-data of
 * [IUTchI] Def 3.1 computed by scripts/infographic/initialtheta-data.js) this runs
 *
 *   src/iut pipeline --theta-json docs/initial-theta-data/<id>.json            (text)
 *   src/iut pipeline --theta-json docs/initial-theta-data/<id>.json --json     (JSON)
 *
 * and writes
 *
 *   docs/initial-theta-data/pipeline/<id>.txt, <id>.json   the state after every stage
 *   docs/PIPELINE.md                                       the table between the "summary" markers
 *   htdocs/data/initial-theta-data.js                      the four input files, for the web app's bench
 *
 * It stops with an error if a pipeline reports a problem (exit status ≠ 0).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..', '..');
const BIN = path.join(ROOT, 'src', 'iut');
const DATA = path.join(ROOT, 'docs', 'initial-theta-data');
const OUT = path.join(DATA, 'pipeline');
const DOC = path.join(ROOT, 'docs', 'PIPELINE.md');
const WEB = path.join(ROOT, 'htdocs', 'data', 'initial-theta-data.js');

if (!fs.existsSync(BIN)) { console.error('build the toolkit first: make -C src'); process.exit(2); }
fs.mkdirSync(OUT, { recursive: true });

function run(args) {
  try { return { code: 0, out: execFileSync(BIN, args, { encoding: 'utf8', maxBuffer: 1 << 26 }) }; }
  catch (e) { return { code: e.status, out: (e.stdout || '') + (e.stderr || '') }; }
}
const f6 = (x) => (typeof x === 'number' ? x.toFixed(6) : String(x));
const g4 = (x) => (typeof x === 'number' ? (Math.abs(x) >= 1e6 ? x.toExponential(3) : x.toFixed(4)) : String(x));

const index = JSON.parse(fs.readFileSync(path.join(DATA, 'index.json'), 'utf8'));
const rows = [], web = [];
for (const ex of index.examples) {
  const file = path.join(DATA, ex.file), rel = path.relative(ROOT, file);
  const txt = run(['pipeline', '--theta-json', file]);
  const js = run(['pipeline', '--json', '--theta-json', file]);
  if (txt.code || js.code) { console.error(txt.out); throw new Error(`${ex.id}: the pipeline reports ${txt.code} problem(s)`); }
  fs.writeFileSync(path.join(OUT, ex.id + '.txt'), `$ iut pipeline --theta-json ${rel}\n\n` + txt.out);
  const P = JSON.parse(js.out);
  fs.writeFileSync(path.join(OUT, ex.id + '.json'), JSON.stringify(P, null, 1) + '\n');
  const H = P.heightBound, G = P.gaussian, L = P.lattice, R = P.multiradial;
  rows.push([
    `[${ex.title}](initial-theta-data/pipeline/${ex.id}.txt)`, ex.curve, String(P.data.l),
    '{' + G.places.map((v) => v.p).join(', ') + '}',
    f6(H.logQ), f6(H.absLogQ), f6(G.thetaPilot), `${L.vertices} / ${L.logLinks + (L.thetaLink ? 1 : 0)}`,
    f6(R.leadingTerm), g4(H.CTheta), `${f6(H.lhs)} ≤ ${g4(H.rhs)}`,
    P.crossCheck.every((c) => c.ok) ? '✓' : '✗', String(P.problems),
  ]);
  web.push({ id: ex.id, title: ex.title, curve: ex.curve, l: ex.l, VbadMod: ex.VbadMod, text: fs.readFileSync(file, 'utf8') });
  console.log(`${ex.id}: ${P.problems} problem(s); log q = ${f6(H.logQ)}, Θ-pilot ${f6(G.thetaPilot)}, C_Θ = ${g4(H.CTheta)}`);
}

/* docs/PIPELINE.md: replace the table between the markers */
const head = ['example', 'curve', 'l', 'V^bad_mod', 'log q', '\\|log q\\|', 'Θ-pilot log-vol.', 'vertices / links', 'Σ leading terms', 'C_Θ', 'Thm 1.10: (1/6) log q ≤ …', 'matches JSON', 'problems'];
const table = ['| ' + head.join(' | ') + ' |', '|' + head.map(() => '---').join('|') + '|', ...rows.map((r) => '| ' + r.join(' | ') + ' |')].join('\n');
const doc = fs.readFileSync(DOC, 'utf8');
const re = /(<!-- summary:start[^>]*-->)[\s\S]*?(<!-- summary:end -->)/;
if (!re.test(doc)) throw new Error('docs/PIPELINE.md lacks the summary markers');
fs.writeFileSync(DOC, doc.replace(re, `$1\n${table}\n$2`));

/* the web app's bench: the four input files */
fs.writeFileSync(WEB, '// generated by scripts/pipeline/build.js from docs/initial-theta-data/*.json — do not edit\n' +
  '// The worked examples of initial Θ-data ([IUTchI] Def 3.1), computed exactly; the page passes the text to\n' +
  '// the engine as `--theta-json <text>`.\n' +
  '(function (root) { root.IUT_THETA_DATA = ' + JSON.stringify(web) + '; })(typeof window !== "undefined" ? window : globalThis);\n');
console.log(`wrote ${path.relative(ROOT, OUT)}/*.txt|json, ${path.relative(ROOT, DOC)}, ${path.relative(ROOT, WEB)}`);
