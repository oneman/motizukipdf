#!/bin/sh
# Compile the C toolkit (src/) to WebAssembly (wasm32-wasi) and wrap it as htdocs/engine/iut.wasm.js,
# a plain script that defines window.IUT_WASM_BASE64 so that index.html works from file:// without fetch().
#
#   scripts/web/build-engine.sh            # needs clang with the wasm32 target, wasm-ld and a WASI libc
#                                          # (Ubuntu: apt install clang lld wasi-libc libclang-rt-18-dev-wasm32)
#   CC=clang-18 WASI_SYSROOT=/usr scripts/web/build-engine.sh
set -e
cd "$(dirname "$0")/../../src"
CC="${CC:-clang}"
SYSROOT="${WASI_SYSROOT:-/usr}"
OUT="../htdocs/engine"
TMP="${TMPDIR:-/tmp}/iut-wasm.$$"
mkdir -p "$OUT"
SRCS="iut_ids.c iut_core.c iut_lattice.c iut_json.c iut_view.c iut_main.c iut_tui.c iut_i.c \
      iut_ops_i.c iut_ops_ii.c iut_ops_iii.c iut_ops_iv.c iut_ops_logic.c iut_proc.c iut_test_ops.c"
# 16 MB stack: the runners keep Hodge theaters and lattices on the stack.
"$CC" --target=wasm32-wasi --sysroot="$SYSROOT" -std=c11 -O2 -DIUT_NO_CURSES \
      -D_POSIX_C_SOURCE=200809L -D_DEFAULT_SOURCE -Wall -Wno-unused-parameter -Wno-unused-but-set-variable \
      -Wl,-z,stack-size=16777216 -o "$TMP" $SRCS -lm
node -e '
const fs = require("fs");
const wasm = fs.readFileSync(process.argv[1]);
const b64 = wasm.toString("base64");
const out = "// generated by scripts/web/build-engine.sh from src/*.c — do not edit\n" +
  "// The C toolkit `iut` compiled to wasm32-wasi (" + wasm.length + " bytes), base64-encoded so that the\n" +
  "// page can be opened directly from index.html (no fetch of a .wasm file).\n" +
  "(function (root) { root.IUT_WASM_BASE64 = \"" + b64 + "\"; })(typeof window !== \"undefined\" ? window : globalThis);\n";
fs.writeFileSync(process.argv[2], out);
console.log("wrote " + process.argv[2] + " (" + wasm.length + " bytes of wasm)");
' "$TMP" "$OUT/iut.wasm.js"
rm -f "$TMP"
