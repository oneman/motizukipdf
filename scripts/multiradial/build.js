    let h = '<table><tr><th>example</th><th>l</th><th>6l(l+5)/(l²+l−12)</th><th>log d<sup>K</sup> (estimate)</th><th>bound on log q</th><th>actual log q</th><th>log q / 6 log d<sup>K</sup></th></tr>';
