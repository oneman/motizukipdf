#!/usr/bin/env node
/*
 * build.js — typeset multiradial_guide.pdf, a long illustrated guide to the multiradial algorithm
 * of inter-universal Teichmüller theory ([IUTchIII] Theorem 3.11 and Corollary 3.12).
 *
 * Sources: docs/multiradial_guide/parts/*.html, concatenated in file-name order. The first part
 * holds <head> and the styles. Math goes between \( … \) (inline) and \[ … \] (display) and is
 * rendered with KaTeX. Three kinds of placeholders are filled in here, so that no number in the
 * guide is typed in by hand:
 *
 *   {{key}}          a number from the pipeline of the running example (1 + 8 = 9, l = 7),
 *                    read from docs/initial-theta-data/pipeline/<id>.json
 *   {{svg:name}}     a figure drawn from the pipeline data of the four worked examples
 *   {{table:name}}   a table built from the same data
 *   {{run:Proc}}     the live output of `src/iut run Proc --theta-json <running example>`
 *
 * Output: multiradial_guide.pdf at the repository root (Chromium via Playwright) and the rendered
 * HTML at build/multiradial_guide.html.
 *
 * Usage:  make -C src && (cd scripts/multiradial && npm ci) && node scripts/multiradial/build.js [--html-only]
 * The pipeline JSON files are regenerated by `node scripts/pipeline/build.js`.
 */
