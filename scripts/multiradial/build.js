    const pl = m.G.places[0];
    let h = `<table><tr><th>j</th><th>j²</th><th>q̲<sup>j²</sup> at v = ${pl.p}: ord<sub>${pl.p}</sub>(q̲<sup>j²</sup>)</th><th>ord<sub>${pl.p}</sub>(q<sup>j²</sup>)</th><th>unit part mod ${pl.p}<sup>${pl.precision}</sup></th><th>log-volume −(j²/2l)·log q</th></tr>`;
